import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {evaluatePlans,quantile} from '../international-dashboard/decision-model.mjs';
const data=JSON.parse(await readFile(new URL('../international-dashboard/assets/data.json',import.meta.url),'utf8'));
const input={country:'Germany',weight:1200,budget:8000,days:30,service:'all',fuel:0,weights:{cost:40,time:35,reliability:25}};
const result=evaluatePlans(data,input);
assert.equal(result.alternatives.length,3);
assert.equal(result.alternatives.find(a=>a.mode==='ROAD').available,false);
assert.ok(result.alternatives.filter(a=>a.available).every(a=>Number.isFinite(a.score)&&a.score>=0&&a.score<=100&&a.days>=a.medianDays));
assert.ok(result.recommended&&result.alternatives.find(a=>a.mode===result.recommended).feasible);
assert.equal(evaluatePlans(data,{...input,budget:1,days:1}).recommended,null);
assert.equal(evaluatePlans(data,{...input,country:'No such destination'}).recommended,null);
assert.throws(()=>evaluatePlans(data,{...input,weights:{cost:0,time:0,reliability:0}}));
assert.throws(()=>evaluatePlans(data,{...input,weight:-1}));
assert.equal(evaluatePlans(data,{...input,weight:1e9}).recommended,null);
const fuel=evaluatePlans(data,{...input,fuel:30});
for(const a of result.alternatives.filter(a=>a.available))assert.ok(fuel.alternatives.find(b=>b.mode===a.mode).cost>a.cost);
assert.equal(evaluatePlans(data,{...input,country:'Malaysia',weight:1000,budget:100000,days:90}).alternatives.filter(a=>a.available).length,3);
assert.equal(quantile([1,2,3,4,5],.5),3);
assert.equal(quantile([], .8),null);
assert.equal(input.fuel,0);
console.log('Decision checks passed: feasibility, unavailable routes, sparse data, fuel sensitivity, weights, and quantiles.');
console.log(JSON.stringify(result.alternatives.map(a=>({mode:a.mode,n:a.n,cost:a.cost,days:a.days,score:a.score,feasible:a.feasible})),null,2));
